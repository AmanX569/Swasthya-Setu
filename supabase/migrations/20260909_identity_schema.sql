  USING (true)
  WITH CHECK (true);

CREATE POLICY IF NOT EXISTS "Service role full access on patient_identities"
  ON patient_identities FOR ALL
  USING (true)
  WITH CHECK (true);

CREATE POLICY IF NOT EXISTS "Service role full access on otp_requests"
  ON otp_requests FOR ALL
  USING (true)
  WITH CHECK (true);

CREATE POLICY IF NOT EXISTS "Service role full access on identity_audit_log"
  ON identity_audit_log FOR ALL
  USING (true)
  WITH CHECK (true);
